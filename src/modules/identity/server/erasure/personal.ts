/** Conversation roots remain so other people's replies are not cascade-deleted. */
export async function eraseAuthoredText(tx: Prisma.TransactionClient, id: number) {
  await tx.postComment.updateMany({ where: { userId: id }, data: { body: '', status: 'DELETED' } })
  await tx.productReview.deleteMany({ where: { userId: id } })
  await tx.productQuestion.updateMany({ where: { userId: id }, data: { userId: null, guestName: '', body: 'حذف‌شده', answer: '' } })
  await tx.itemReview.deleteMany({ where: { userId: id } })
  await tx.forumPostRevision.deleteMany({ where: { userId: id } })
  await tx.forumPost.updateMany({ where: { userId: id }, data: { content: '', status: 'HIDDEN', reviewReason: '' } })
  await tx.forumThread.updateMany({ where: { userId: id }, data: { title: 'گفت‌وگوی حساب حذف‌شده' } })
  await tx.forumMessage.updateMany({ where: { userId: id }, data: { content: '' } })
  await tx.communityPost.updateMany({ where: { authorId: id }, data: { content: '', status: 'DELETED' } })
  await tx.communityComment.updateMany({ where: { authorId: id }, data: { content: '', status: 'DELETED' } })
  await tx.communityLike.deleteMany({ where: { userId: id } })
  await tx.communityReport.deleteMany({ where: { reporterId: id } })
}
