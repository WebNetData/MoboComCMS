/* Actual offline corpus/ignore/incremental behavior, without touching app source. */
const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process'),assert=require('node:assert/strict');
const adapter=require('./graphify-local.cjs');
const fixture=path.join(adapter.local,`validation-${Date.now()}`);
fs.mkdirSync(path.join(fixture,'src'),{recursive:true});
const git=cp.spawnSync('git',['init','--quiet',fixture],{encoding:'utf8',windowsHide:true});
assert.equal(git.status,0);
fs.copyFileSync(path.join(adapter.root,'.graphifyignore'),path.join(fixture,'.graphifyignore'));
fs.writeFileSync(path.join(fixture,'.gitignore'),'src/ignored.ts\n');
const marker='CONFIDENTIAL_CANARY_DO_NOT_INDEX_20261010';
for(const file of ['.env','config.ts','document.md','src/private.json','src/private.pem','src/ignored.ts','src/secrets.ts']) fs.writeFileSync(path.join(fixture,file),`export const confidential = '${marker}'`);
const a=path.join(fixture,'src/a.ts'),b=path.join(fixture,'src/b.ts');
fs.writeFileSync(a,'export function registryFixture() { return 1 }\n');
const args=['extract',fixture,'--code-only','--no-cluster','--no-dedup','--max-workers','2','--out',fixture];
const gp=path.join(fixture,'graphify-out','graph.json');
const read=()=>JSON.parse(fs.readFileSync(gp,'utf8'));
const has=(label)=>read().nodes.some(n=>n.label===label);
const measures=[];
measures.push(adapter.run(args,'validation-initial'));
assert(has('registryFixture()'));
const manifest=()=>Object.keys(JSON.parse(fs.readFileSync(path.join(fixture,'graphify-out','manifest.json'),'utf8')));
assert.deepEqual(manifest(),['src/a.ts']);
assert(!fs.readFileSync(gp,'utf8').includes(marker));
fs.writeFileSync(b,"import { registryFixture } from './a'; export function registryConsumer() { return registryFixture() }\n");
measures.push(adapter.run(args,'validation-add'));
assert(has('registryConsumer()'));
assert(read().edges.some(e=>e.relation==='calls'&&e.source.includes('registryconsumer')&&e.target.includes('registryfixture')));
fs.writeFileSync(a,'export function registryFixtureChanged() { return 2 }\n');
measures.push(adapter.run(args,'validation-change'));
assert(has('registryFixtureChanged()'));
assert(!has('registryFixture()'),'Removed definition must be pruned (an unresolved import reference may remain under a different label)');
fs.unlinkSync(b);
measures.push(adapter.run(args,'validation-delete'));
assert(!has('registryConsumer()'));
assert.deepEqual(manifest(),['src/a.ts']);
assert.equal(read().input_tokens,0);assert.equal(read().output_tokens,0);
const toolDir=cp.spawnSync('uv',['tool','dir'],{encoding:'utf8',windowsHide:true}).stdout.trim();
const py=path.join(toolDir,'graphifyy',process.platform==='win32'?'Scripts/python.exe':'bin/python');
const network=cp.spawnSync(py,['-c',"import socket; socket.create_connection(('example.com',443))"],{
 encoding:'utf8',windowsHide:true,env:{...process.env,PYTHONPATH:path.join(adapter.root,'tools/devstack/graphify-offline'),MOBOCOM_GRAPHIFY_OFFLINE:'1'}});
assert.notEqual(network.status,0);assert.match(network.stderr,/local code-only: network disabled/);
const skip=adapter.refresh();assert.equal(skip.skipped,true);
const result={status:'passed',checks:['project source allowlist','gitignore','secret/config/document exclusion','network blocked','AST relationships','incremental add/change/delete','unchanged refresh skips extraction','zero semantic tokens'],fixture,measures};
fs.writeFileSync(path.join(adapter.local,'validation.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify({status:result.status,checks:result.checks,runs:measures.map(m=>({ms:m.durationMs,memory:m.sampledPeakProcessTreeWorkingSetBytes}))}));
