// Purchase orders reuse the stock receipt transaction: partial receiving, replay, over-receipt and rollback stay atomic.
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { PrismaClient } = require('@prisma/client')
assert(/test|check|store_experiences_/i.test(new URL(process.env.DATABASE_URL).pathname), 'disposable database required')
const db = new PrismaClient(), stamp = `purchase-${Date.now().toString(36)}`
const load = require('./connected-source-loader.cjs')({ '@/platform/database/prisma': { db } })
const purchasing = load('src/modules/catalog/server/purchasing.ts')
const locations = load('src/modules/catalog/server/locations.ts')
const created = { products: [], purchases: [], receipts: [] }

;(async () => {
  const locationId = await db.$transaction(tx => locations.defaultLocationId(tx))
  const product = await db.product.create({ data: { name: `${stamp}-item`, slug: `${stamp}-item`, sku: `${stamp}-item`, kind: 'PHYSICAL', active: true, price: 2000, priceMinor: 2000n, costMinor: 500n, currency: 'IRT', stock: 0 } })
  created.products.push(product.id)
  const purchase = await purchasing.createPurchase({ requestId: randomUUID(), locationId, supplier: `${stamp}-supplier`, lines: [{ productId: product.id, quantity: 10, unitCost: '1000' }] }, null)
  created.purchases.push(purchase.id)
  let detail = await purchasing.purchaseDetail(purchase.id)
  const lineId = detail.purchase.lines[0].id
  const failedKey = randomUUID()
  await assert.rejects(purchasing.receivePurchase({ purchaseId: purchase.id, version: 0, requestId: failedKey, lines: [{ lineId, quantity: 4 }] }, null, async () => { throw Error('audit rollback') }), /audit rollback/)
  detail = await purchasing.purchaseDetail(purchase.id)
  assert.equal(detail.purchase.status, 'OPEN')
  assert.equal(detail.purchase.lines[0].receivedQuantity, 0)
  assert.equal(await db.stockReceipt.count({ where: { requestId: failedKey } }), 0)

  const request = { purchaseId: purchase.id, version: 0, requestId: randomUUID(), lines: [{ lineId, quantity: 4 }] }
  const first = await purchasing.receivePurchase(request, null)
  created.receipts.push(first.receiptId)
  assert.equal(first.replayed, false)
  assert.equal(first.status, 'PARTIAL')
  await assert.rejects(purchasing.receivePurchase({ purchaseId: purchase.id, version: 1, requestId: randomUUID(), lines: [{ lineId, quantity: 7 }] }, null), /بیشتر/)
  const final = await purchasing.receivePurchase({ purchaseId: purchase.id, version: 1, requestId: randomUUID(), lines: [{ lineId, quantity: 6 }] }, null)
  created.receipts.push(final.receiptId)
  assert.equal(final.status, 'RECEIVED')
  const replay = await purchasing.receivePurchase(request, null)
  assert.equal(replay.replayed, true, 'same-key retry is returned after the purchase became terminal')
  assert.equal(replay.receiptId, first.receiptId)
  detail = await purchasing.purchaseDetail(purchase.id)
  assert.equal(detail.purchase.lines[0].receivedQuantity, 10)
  assert.equal(await db.stockReceipt.count({ where: { purchaseReceipt: { purchaseId: purchase.id } } }), 2)
  assert.equal((await db.locationStock.findFirst({ where: { locationId, productId: product.id } })).quantity, 10)

  const concurrent = await purchasing.createPurchase({ requestId: randomUUID(), locationId, supplier: `${stamp}-race`, lines: [{ productId: product.id, quantity: 5, unitCost: '1200' }] }, null)
  created.purchases.push(concurrent.id)
  const concurrentLine = (await purchasing.purchaseDetail(concurrent.id)).purchase.lines[0]
  const raced = await Promise.allSettled([1, 2].map(() => purchasing.receivePurchase({ purchaseId: concurrent.id, version: 0, requestId: randomUUID(), lines: [{ lineId: concurrentLine.id, quantity: 3 }] }, null)))
  const winners = raced.filter(row => row.status === 'fulfilled')
  assert.equal(winners.length, 1, 'only one stale-version receive can claim the purchase')
  created.receipts.push(winners[0].value.receiptId)
  assert.equal((await purchasing.purchaseDetail(concurrent.id)).purchase.lines[0].receivedQuantity, 3)
  await assert.rejects(purchasing.createPurchase({ requestId: randomUUID(), locationId, supplier: `${stamp}-cap`, lines: [{ productId: product.id, quantity: 1_000_000, unitCost: '9999999999999' }] }, null), /بیش از حد مجاز/, 'oversized total is a validation error, not a BIGINT failure')
  const cancelled = await purchasing.cancelPurchase({ purchaseId: concurrent.id, version: 1 })
  assert.equal(cancelled.replayed, false)
  assert.equal((await purchasing.cancelPurchase({ purchaseId: concurrent.id, version: 1 })).replayed, true, 'retried cancel after a lost response succeeds once')
  const priced = await purchasing.createPurchase({ requestId: randomUUID(), locationId, supplier: `${stamp}-currency`, lines: [{ productId: product.id, quantity: 2, unitCost: '1000' }] }, null)
  created.purchases.push(priced.id)
  const pricedLine = (await purchasing.purchaseDetail(priced.id)).purchase.lines[0]
  await db.product.update({ where: { id: product.id }, data: { currency: 'USD' } })
  await assert.rejects(purchasing.receivePurchase({ purchaseId: priced.id, version: 0, requestId: randomUUID(), lines: [{ lineId: pricedLine.id, quantity: 1 }] }, null), /واحد پول/, 'frozen cost is never reinterpreted in a changed product currency')
  await db.product.update({ where: { id: product.id }, data: { currency: 'IRT' } })
  assert.equal((await purchasing.purchaseDetail(priced.id)).purchase.lines[0].receivedQuantity, 0)
  console.log('stock purchases: ok')
})().catch(error => { console.error(error); process.exitCode = 1 }).finally(async () => {
  await db.stockPurchaseReceipt.deleteMany({ where: { purchaseId: { in: created.purchases } } })
  await db.stockReceipt.deleteMany({ where: { id: { in: created.receipts } } })
  await db.stockMovement.deleteMany({ where: { productId: { in: created.products } } })
  await db.locationStock.deleteMany({ where: { productId: { in: created.products } } })
  await db.stockPurchase.deleteMany({ where: { id: { in: created.purchases } } })
  await db.product.deleteMany({ where: { id: { in: created.products } } })
  await db.$disconnect()
})
