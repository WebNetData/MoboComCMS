// Actual localhost UI with namespaced PostgreSQL fixtures; credentials are never logged.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict'), { chromium, expect } = require('@playwright/test')
const baseURL = process.env.E2E_BASE_URL || 'http://localhost:3000'
if (new URL(baseURL).hostname !== 'localhost' || !process.env.MOBOCOM_BUSINESS_FIXTURE) throw Error('Owned localhost business fixture required')
async function main() {
  const fixture = JSON.parse(process.env.MOBOCOM_BUSINESS_FIXTURE), browser = await chromium.launch({ headless: true }), errors = [], output = process.env.E2E_OUTPUT_DIR || '/tmp/business-completion-evidence'
  fs.mkdirSync(output, { recursive: true })
  const context = async token => { const result = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1100 }, extraHTTPHeaders: { origin: baseURL } }); if (token) await result.addCookies([{ name: 'next-auth.session-token', value: token, url: baseURL }]); return result }
  const staff = await context(fixture.staffToken), member = await context(fixture.memberToken), guest = await context()
  try {
    for (const id of ['businesses', 'reviews']) assert.equal((await staff.request.patch('/api/admin/extensions', { data: { id, enabled: true } })).status(), 200)
    const admin = await staff.newPage(), page = await member.newPage(), publicPage = await guest.newPage()
    for (const view of [admin, page, publicPage]) view.on('pageerror', error => errors.push(error.message))
    const visit = async (view, route) => { await view.goto(route, { waitUntil: 'domcontentloaded', timeout: 180000 }); await view.locator('main').first().waitFor({ timeout: 60000 }) }
    await visit(publicPage, `/businesses/${fixture.slug}`)
    await expect(publicPage.getByText('امتیازهای جزئی', { exact: true })).toHaveCount(0) // guest has summary but no write controls
    await expect(publicPage.getByText('برای ثبت تجربه', { exact: false })).toBeVisible()
    assert.equal((await guest.request.post('/api/businesses', { data: { action: 'request', kind: 'CLAIM', businessId: fixture.businessId, note: 'درخواست آزمایشی مهمان بدون اجازه نباید ثبت شود' } })).status(), 401)
    assert.equal((await member.request.post('/api/admin/businesses', { data: { action: 'request.decide', requestId: 1, decision: 'APPROVED' } })).status(), 403)
    await visit(page, '/businesses?q=' + encodeURIComponent('آوان'))
    await expect(page.getByRole('link', { name: 'تجربهٔ خرید آزمایشی آوان', exact: true })).toBeVisible()
    await page.locator('#suggest-business > summary').click()
    const suggestion = page.locator('#suggest-business')
    await suggestion.getByLabel('نام کسب‌وکار', { exact: true }).fill('کسب‌وکار پیشنهادی آزمون')
    await suggestion.getByLabel('نشانی وب‌سایت', { exact: true }).fill(`https://${fixture.stamp}-suggest.example`)
    await suggestion.getByLabel('چرا این کسب‌وکار را پیشنهاد می‌دهید؟', { exact: true }).fill('این درخواست یک آزمون واقعی از جریان معرفی و بررسی کسب‌وکار است.')
    await suggestion.getByRole('button', { name: 'ارسال پیشنهاد', exact: true }).click()
    await expect(suggestion.getByRole('status')).toContainText('درخواست ثبت شد', { timeout: 30000 })
    await visit(page, '/businesses/activity')
    await expect(page.getByText('کسب‌وکار پیشنهادی آزمون', { exact: true })).toBeVisible()
    await visit(admin, '/admin/businesses')
    await expect(admin.getByTestId('business-admin')).toBeVisible({ timeout: 60000 })
    const request = admin.locator('details.sa-card').filter({ hasText: 'کسب‌وکار پیشنهادی آزمون' })
    await request.locator('summary').click()
    await request.locator('[name=slug]').fill(`${fixture.stamp}-suggest`)
    await request.locator('[name=decisionNote]').fill('نام و دامنه بررسی شد و درخواست برای آزمون تأیید می‌شود.')
    await request.getByRole('button', { name: 'تأیید و انتشار کسب‌وکار' }).click()
    await expect(request).toHaveCount(0, { timeout: 30000 })
    await visit(page, '/businesses/activity')
    await expect(page.getByText('تأییدشده', { exact: true })).toBeVisible()
    await visit(page, `/businesses/${fixture.slug}`)
    const reviewForm = page.locator('#write-experience')
    await reviewForm.locator('.rv-picker input[value="4"]').check()
    await reviewForm.locator('details > summary').click()
    await reviewForm.locator('[name=score-quality]').selectOption('5')
    await reviewForm.locator('[name=score-support]').selectOption('4')
    await reviewForm.locator('[name=body]').fill('این تجربهٔ خرید آزمایشی برای بررسی ثبت امتیازهای جزئی و حفظ جریان بررسی مدیریت است.')
    await reviewForm.getByRole('button', { name: 'ثبت تجربهٔ خرید', exact: true }).click()
    await expect(reviewForm.getByRole('status')).toContainText('ثبت شد', { timeout: 30000 })
    await visit(admin, '/admin/businesses')
    const pending = admin.locator('article.sa-card').filter({ hasText: 'این تجربهٔ خرید آزمایشی برای بررسی ثبت امتیازهای جزئی' })
    await expect(pending).toBeVisible({ timeout: 30000 })
    await pending.getByRole('button', { name: 'انتشار تجربه', exact: true }).click()
    await expect(pending).toHaveCount(0, { timeout: 30000 })
    await visit(publicPage, `/businesses/${fixture.slug}`)
    await expect(publicPage.getByText('این تجربهٔ خرید آزمایشی برای بررسی ثبت امتیازهای جزئی', { exact: false })).toBeVisible()
    await publicPage.getByRole('link', { name: 'نمایش تجربه‌های با امتیاز 1', exact: true }).click()
    await expect(publicPage).toHaveURL(/stars=1/)
    await expect(publicPage.locator('article').first()).toBeVisible()
    await visit(page, `/businesses/${fixture.slug}`)
    const helpful = page.getByRole('button', { name: /مفید بود/ }).first()
    await helpful.click(); await expect(helpful).toHaveAttribute('aria-pressed', 'true')
    await page.getByRole('navigation', { name: 'صفحه‌بندی تجربه‌ها', exact: true }).getByRole('link', { name: 'بعد', exact: true }).click()
    await expect(page).toHaveURL(/page=2/)
    await expect(page.locator('article')).toHaveCount(3)
    await visit(page, `/businesses/${fixture.slug}`)
    await page.locator('#claim-business > summary').click()
    const claim = page.locator('#claim-business')
    await claim.locator('[name=note]').fill('من نمایندهٔ این کسب‌وکار آزمایشی هستم و درخواست بررسی مستقل ارتباط حساب را دارم.')
    await claim.getByRole('button', { name: 'ارسال درخواست بررسی نمایندگی', exact: true }).click()
    await expect(claim.getByRole('status')).toContainText('درخواست ثبت شد', { timeout: 30000 })
    await visit(admin, '/admin/businesses')
    const claimReview = admin.locator('details.sa-card').filter({ hasText: 'تجربهٔ خرید آزمایشی آوان' })
    await claimReview.locator('summary').click()
    await claimReview.locator('[name=decisionNote]').fill('ارتباط حساب با کسب‌وکار برای این آزمون به صورت مستقل بررسی شد.')
    await claimReview.locator('[name=acknowledgeRepresentative]').check()
    await claimReview.getByRole('button', { name: 'تأیید نمایندگی', exact: true }).click()
    await expect(claimReview).toHaveCount(0, { timeout: 30000 })
    await visit(page, `/businesses/${fixture.slug}`)
    await expect(page.getByText('شما نمایندهٔ این کسب‌وکار هستید', { exact: false })).toBeVisible()
    const reply = page.locator('article').filter({ hasText: 'این متن فقط یک تجربهٔ آزمایشی' }).first()
    await reply.locator('details > summary').click()
    await reply.locator('[name=reply]').fill('از ثبت تجربهٔ شما سپاسگزاریم؛ این پاسخ از نمایندهٔ بررسی‌شده در آزمون است.')
    await reply.getByRole('button', { name: 'ثبت پاسخ', exact: true }).click()
    await expect(reply.getByRole('status')).toContainText('ذخیره شد', { timeout: 30000 })
    await visit(publicPage, `/businesses/${fixture.slug}`)
    await expect(publicPage.getByText('از ثبت تجربهٔ شما سپاسگزاریم؛ این پاسخ از نمایندهٔ بررسی‌شده در آزمون است.', { exact: true })).toBeVisible()
    for (const [route, label] of [['/businesses?q=' + encodeURIComponent('آوان'), 'directory'], [`/businesses/${fixture.slug}`, 'profile'], ['/businesses/activity', 'activity']]) {
      for (const [theme, width] of [['dark', 1440], ['light', 1440], ['dark', 390], ['light', 390]]) {
        await member.addCookies([{ name: 'theme', value: theme, url: baseURL }])
        await page.setViewportSize({ width, height: 1100 }); await visit(page, route)
        await page.waitForFunction(theme => document.documentElement.dataset.theme === theme, theme)
        await page.evaluate(() => document.fonts.ready)
        await page.screenshot({ path: path.join(output, `${label}-${theme}-${width}.png`), fullPage: true })
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `${label} no overflow at ${width}`)
        if (process.env.E2E_AXE_PATH) {
          await page.evaluate(fs.readFileSync(process.env.E2E_AXE_PATH, 'utf8'))
          const violations = await page.evaluate(async () => (await window.axe.run(document.querySelector('main'), { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations.map(row => ({ id: row.id, nodes: row.nodes.map(node => ({ target: node.target, summary: node.failureSummary })) })))
          assert.deepEqual(violations, [], `${label} ${theme} ${width} scoped accessibility`)
        }
      }
    }
    for (const [theme, width] of [['dark', 1440], ['light', 1440], ['dark', 390]]) {
      await staff.addCookies([{ name: 'theme', value: theme, url: baseURL }]); await admin.setViewportSize({ width, height: 1100 })
      await visit(admin, '/admin/businesses')
      await expect(admin.getByTestId('business-admin')).toBeVisible({ timeout: 30000 })
      await admin.getByRole('button', { name: 'کسب‌وکار تازه', exact: true }).click()
      await admin.screenshot({ path: path.join(output, `admin-${theme}-${width}.png`), fullPage: true })
      assert.equal(await admin.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, 'Admin no overflow')
      if (process.env.E2E_AXE_PATH) { await admin.evaluate(fs.readFileSync(process.env.E2E_AXE_PATH, 'utf8')); assert.deepEqual(await admin.evaluate(async () => (await window.axe.run(document.querySelector('[data-testid=business-admin]'), { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations.map(row => ({ id: row.id, nodes: row.nodes.map(node => ({ target: node.target, summary: node.failureSummary })) }))), [], 'Admin accessibility') }
    }
    assert.deepEqual(errors, [], 'no runtime errors')
    console.log('Business UI passed: real suggestion→staff decision→private result, dimension review→moderation→public display, helpful vote, pagination, reviewed representative claim→official reply, guest/section-only denial, rating filter; directory/profile/activity1440+390 light/dark and Admin1440 light/dark+390 dark with scoped axe and overflow checks.')
  } catch (error) {
    for (const [index, ctx] of browser.contexts().entries()) for (const view of ctx.pages()) await view.screenshot({ path: path.join(output, `failure-${index}.png`), fullPage: true }).catch(() => {})
    throw error
  } finally {
    for (const id of ['businesses', 'reviews']) await staff.request.patch('/api/admin/extensions', { data: { id, enabled: fixture.originalEnabled[id] } }).catch(() => {})
    await browser.close()
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1 })
