const { test } = require('node:test'), assert = require('node:assert/strict'), source = require('./connected-source-loader.cjs')
test('smart sales: attribution window rate, lift and bounded report periods', () => {
  const s = source()('src/modules/ai/domain/sales.ts')
  assert.equal(s.windowRate(0, 30), 0)
  assert.equal(s.windowRate(1, 30), 1)
  const weekly = s.windowRate(0.3, 30)
  assert(weekly > 0.07 && weekly < 0.3, String(weekly))
  assert.equal(s.windowRate(0.3, 7), 0.3)
  assert.equal(s.lift(0.2, 0.1), 1)
  assert.equal(s.lift(0.05, 0.1), -0.5)
  assert.equal(s.lift(0.2, 0), null)
  assert.equal(s.reportDays('90'), 90)
  assert.equal(s.reportDays('365'), 30)
})
test('smart sales: campaign copy is bounded text with no links or markup, and the prompt forbids invented offers', () => {
  const s = source()('src/modules/ai/domain/sales.ts')
  const ok = s.parseCampaignDraft('```json\n' + JSON.stringify({ title: 'تازه‌های هدفون', body: 'مدل‌های تازه رسید.', sms: 'هدفون‌های تازه رسید', subject: 'تازه‌ها' }) + '\n```')
  assert.equal(ok.sms, 'هدفون‌های تازه رسید')
  assert.equal(s.parseCampaignDraft(JSON.stringify({ title: 'ا'.repeat(100), body: 'b', sms: 'c', subject: 'd' })).title.length, 60)
  for (const bad of ['nope', JSON.stringify({ title: 'a', body: '<script>', sms: 'c', subject: 'd' }), JSON.stringify({ title: 'a', body: 'https://x.y', sms: 'c', subject: 'd' }), JSON.stringify({ title: '', body: 'b', sms: 'c', subject: 'd' })]) assert.throws(() => s.parseCampaignDraft(bad))
  const prompt = s.campaignPrompt({ brand: 'B', category: 'هدفون', products: ['A'], audience: 4, offer: '' })
  assert.match(prompt, /نساز/)
  assert.match(prompt, /JSON/)
})
