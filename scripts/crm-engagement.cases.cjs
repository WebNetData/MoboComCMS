const {test}=require('node:test'),assert=require('node:assert/strict'),load=require('./connected-source-loader.cjs')()
const rules=load('src/modules/automation/domain/engagement.ts'),clock=load('src/modules/automation/domain/engagement-clock.ts'),jalali=load('src/shared/time/jalali.ts')
const journey=(patch={})=>({id:'owned-journey-01',name:'Birthday',kind:'birthday',enabled:false,title:'Hello {name}',body:'From {brand}',href:'/dashboard',channels:['sms'],segment:'all',tags:[],productId:0,cadenceDays:0,inactiveDays:30,purchaseQuietDays:30,startsOn:'',endsOn:'',...patch})
test('CRM starts off, every old member needs an affirmative choice, and unknown channels/targets cannot enter a journey',()=>{
 assert.deepEqual(rules.normalizeEngagement({}),rules.ENGAGEMENT_DEFAULTS)
 assert.throws(()=>rules.normalizeEngagement({birthdayCalendar:'unknown'}))
 assert.throws(()=>rules.normalizeEngagement({journeys:[journey({channels:'sms'})]}))
 assert.throws(()=>rules.normalizeEngagement({journeys:[journey({tags:'everyone'})]}))
 assert.throws(()=>rules.normalizeEngagement({journeys:[journey({channels:['shell']})]}))
 assert.throws(()=>rules.normalizeEngagement({journeys:[journey({href:'//elsewhere.test'})]}))
 assert.throws(()=>rules.normalizeEngagement({journeys:[journey({href:'javascript:alert(1)'})]}))
 assert.throws(()=>rules.normalizeEngagement({journeys:[journey({kind:'run-code'})]}))
 assert.throws(()=>rules.normalizeEngagement({journeys:[journey({kind:'product-interest'})]}),'follow offer needs an actual product')
})
