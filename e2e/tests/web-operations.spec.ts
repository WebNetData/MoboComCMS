test('server panel unlock, certificate import, database backup and updates share protected owners', async ({ browser, baseURL }, info) => {
  test.setTimeout(240_000)
  expect(baseURL).toBe('http://localhost:3205')
  const f = fixture(), context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' })
  try {
    await context.addCookies([{ name: 'next-auth.session-token', value: f.owner.token, url: baseURL! }, { name: 'mc-translate-dismissed', value: '1', url: baseURL! }])
    expect((await context.request.get('/api/admin/server/domains')).status()).toBe(401)
    expect((await context.request.post('/api/admin/updates', { headers: { Origin: baseURL! }, data: { op: 'migrate' } })).status()).toBe(401)
    const page = await context.newPage(), errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
    await page.goto('/admin/server/domains')
    await page.getByLabel('رمز عبور', { exact: true }).fill('wrong password')
    await page.getByRole('button', { name: 'باز کردن پنل', exact: true }).click()
    await expect(page.getByText('رمز عبور درست نیست', { exact: true })).toBeVisible()
    await page.getByLabel('رمز عبور', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'باز کردن پنل', exact: true }).click()
    await page.getByRole('button', { name: /^گواهی SSL/ }).click()
    const issue = page.locator('form').filter({ has: page.getByRole('heading', { name: 'گرفتن گواهی تازه' }) })
    await issue.getByRole('radio', { name: /DNS کلادفلر/ }).check()
    await expect(issue.getByRole('checkbox', { name: /Wildcard/ })).toBeVisible()
    await issue.getByRole('radio', { name: /Standalone/ }).check()
    await expect(issue.getByRole('checkbox', { name: /Wildcard/ })).toHaveCount(0)
    const upload = page.locator('form').filter({ has: page.getByRole('heading', { name: 'بارگذاری گواهی خودتان' }) })
    await upload.getByLabel('دامنهٔ گواهی', { exact: true }).fill('example.com')
    await upload.locator('input[type=file]').nth(0).setInputFiles({ name: 'cert.pem', mimeType: 'application/x-pem-file', buffer: Buffer.from(f.owner.certificate) })
    await upload.locator('input[type=file]').nth(1).setInputFiles({ name: 'key.pem', mimeType: 'application/x-pem-file', buffer: Buffer.from(f.owner.privateKey) })
    await upload.getByRole('button', { name: 'اعتبارسنجی و ذخیرهٔ امن', exact: true }).click()
    await expect(upload.getByText(/manual-example.com ذخیره شد/)).toBeVisible()
    await expect(page.locator('table').getByText('manual-example.com', { exact: true })).toBeVisible()
    expect((await context.request.post('/api/admin/server/domains', { headers: { Origin: 'https://foreign.invalid' }, data: { op: 'cert-delete', name: 'manual-example.com' } })).status()).toBe(403)
    for (const theme of ['light', 'dark']) for (const width of [1440, 390]) {
      await context.addCookies([{ name: 'theme', value: theme, url: baseURL! }]); await page.setViewportSize({ width, height: 1100 })
      await page.goto('/admin/server/domains'); await page.getByRole('button', { name: /^گواهی SSL/ }).click()
      await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
      await page.evaluate(source => { const script = document.createElement('script'); script.nonce = document.querySelector<HTMLScriptElement>('script[nonce]')?.nonce || ''; script.textContent = source; document.head.append(script) }, fs.readFileSync(require.resolve('axe-core/axe.min.js'), 'utf8'))
      const violations = await page.evaluate(async () => (await (window as any).axe.run(document.querySelector('.sa-cols'), { iframes: false, runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations)
      expect(violations).toEqual([])
      await page.screenshot({ path: info.outputPath(`ssl-${theme}-${width}.png`), fullPage: true })
    }
    await page.goto('/admin/server/database')
    await expect(page.getByRole('heading', { name: 'بکاپ دستی و بازیابی', exact: true })).toBeVisible()
    const before = await (await context.request.get('/api/admin/server/backups')).json()
    const previousIds = before.backups.map((item: { id: string }) => item.id)
    await page.getByRole('button', { name: 'گرفتن بکاپ اکنون', exact: true }).click()
    await expect(page.getByText(/بکاپ در صف اجرا قرار گرفت/)).toBeVisible()
    await expect.poll(async () => {
      const result = await (await context.request.get('/api/admin/server/backups')).json()
      return result.state?.status === 'SUCCESS' && !previousIds.includes(result.state.backupId)
    }, { timeout: 120_000, intervals: [1000, 2000, 4000] }).toBe(true)
    const backups = await (await context.request.get('/api/admin/server/backups')).json()
    expect(backups.backups.length).toBeGreaterThan(0)
    const restore = await context.request.post('/api/admin/server/backups', { headers: { Origin: baseURL! }, data: { action: 'restore-test', id: backups.state.backupId } })
    expect(restore.ok()).toBe(true); expect((await restore.json()).result.ok).toBe(true)
    await page.getByRole('button', { name: 'تازه‌سازی وضعیت', exact: true }).click()
    await page.screenshot({ path: info.outputPath('database-backup.png'), fullPage: true })
    await page.goto('/admin/updates')
    await expect(page.getByRole('heading', { name: 'به‌روزرسانی سایت', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'قفل کن', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'پنل سرور قفل است', exact: true })).toBeVisible()
    expect((await context.request.post('/api/admin/server/updates', { headers: { Origin: baseURL! }, data: { op: 'apply', ref: 'v0.1.0', backupConfirmed: true } })).status()).toBe(401)
    expect(errors).toEqual([])
  } finally { await context.close() }
})
