import fs from 'node:fs'
import { test, expect } from '@playwright/test'

test.skip(!process.env.E2E_PACKAGE_FIXTURE, 'owned package-update lab required')
test('signed package admission, locked/scoped/origin refusal and web launch in four themes/sizes', async ({ browser, baseURL }, info) => {
  test.setTimeout(240_000)
  expect(baseURL).toBe('http://localhost:3205')
  const fixture = JSON.parse(fs.readFileSync(process.env.E2E_PACKAGE_FIXTURE!, 'utf8'))
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' })
  const visitor = await browser.newContext({ baseURL }), section = await browser.newContext({ baseURL })
  try {
    expect((await visitor.request.post('/api/admin/server/updates/package', { headers: { Origin: baseURL!, 'Content-Type': 'application/octet-stream' }, data: 'invalid' })).status()).toBe(403)
    await section.addCookies([{ name: 'next-auth.session-token', value: fixture.section, url: baseURL! }])
    expect((await section.request.post('/api/admin/server/updates/package', { headers: { Origin: baseURL!, 'Content-Type': 'application/octet-stream' }, data: 'invalid' })).status()).toBe(403)
    await context.addCookies([{ name: 'next-auth.session-token', value: fixture.owner, url: baseURL! }, { name: 'mc-translate-dismissed', value: '1', url: baseURL! }])
    expect((await context.request.post('/api/admin/server/updates/package', { headers: { Origin: baseURL!, 'Content-Type': 'application/octet-stream' }, data: 'invalid' })).status()).toBe(401)
    const page = await context.newPage(), errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/admin/updates')
    await page.getByLabel('رمز عبور', { exact: true }).fill('Owned-Web-Operations-Quartz-2049')
    await page.getByRole('button', { name: 'باز کردن پنل', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'نصب بستهٔ به‌روزرسانی', exact: true })).toBeVisible()
    expect((await context.request.post('/api/admin/server/updates/package', { headers: { Origin: '', 'Content-Type': 'application/octet-stream' }, data: 'invalid' })).status()).toBe(403)
    expect((await context.request.post('/api/admin/server/updates/package', { headers: { Origin: 'https://foreign.invalid', 'Content-Type': 'application/octet-stream' }, data: 'invalid' })).status()).toBe(403)
    const input = page.getByLabel('فایل انتشار موبوکام', { exact: true })
    await input.setInputFiles({ name: 'tampered.mbrelease', mimeType: 'application/octet-stream', buffer: Buffer.from('not a signed release') })
    await page.getByRole('button', { name: 'بارگذاری و بررسی بسته', exact: true }).click()
    await expect(page.getByText(/امضا یا محتوای بسته معتبر نیست/)).toBeVisible()
    const packageFile = fs.readFileSync(fixture.package)
    expect(packageFile.length).toBeGreaterThan(10 * 1024 * 1024)
    await input.setInputFiles({ name: 'mobocom-1.6.1.mbrelease', mimeType: 'application/octet-stream', buffer: packageFile })
    await page.getByRole('button', { name: 'بارگذاری و بررسی بسته', exact: true }).click()
    await expect(page.getByText(/امضای بستهٔ نسخهٔ 1.6.1 تأیید شد/)).toBeVisible({ timeout: 90_000 })
    const card = page.locator('.upd-package')
    await expect(card.getByRole('button', { name: 'نصب نسخهٔ 1.6.1', exact: true })).toBeDisabled()
    await page.reload()
    await expect(card.getByRole('button', { name: 'نصب نسخهٔ 1.6.1', exact: true })).toBeVisible()
    await card.getByText('مشخصات صحت و ناشر', { exact: true }).click()
    for (const [theme, width] of [['light', 1440], ['dark', 1440], ['light', 390], ['dark', 390]] as const) {
      await page.setViewportSize({ width, height: 1100 })
      await page.evaluate(t => { document.documentElement.dataset.theme = t; document.documentElement.classList.toggle('dark', t === 'dark') }, theme)
      expect(await card.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
      await page.addScriptTag({ path: require.resolve('axe-core/axe.min.js') })
      const violations = await card.evaluate(async element => (await (window as unknown as { axe: { run: (scope: Element, options: unknown) => Promise<{ violations: unknown[] }> } }).axe.run(element, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations)
      expect(violations).toEqual([])
      await page.screenshot({ path: info.outputPath(`package-${theme}-${width}.png`), fullPage: true })
    }
    await card.getByRole('checkbox', { name: /تأیید می‌کنم پشتیبان اجباری/ }).check()
    page.once('dialog', dialog => dialog.accept())
    await card.getByRole('button', { name: 'نصب نسخهٔ 1.6.1', exact: true }).click()
    await expect(page.getByText('به‌روزرسانی کامل شد. صفحه را تازه کنید.', { exact: true })).toBeVisible({ timeout: 30_000 })
    await expect(page.getByRole('heading', { name: 'به‌روزرسانی سایت', exact: true })).toBeVisible()
    expect(errors).toEqual([])
  } finally { await Promise.all([context.close(), visitor.close(), section.close()]) }
})
