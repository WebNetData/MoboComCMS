import fs from 'node:fs'
import { test, expect } from '@playwright/test'

test.skip(!process.env.E2E_HOST_SETUP_FIXTURE, 'owned isolated HTTPS/first-owner fixture required')

test('browser configures domain/SSL, recovers an issuance failure, survives restart and creates one canonical owner', async ({ page, request, baseURL }, info) => {
  test.setTimeout(240_000)
  expect(baseURL).toBe('https://localhost:3226')
  const fixture = JSON.parse(fs.readFileSync(process.env.E2E_HOST_SETUP_FIXTURE!, 'utf8'))
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  expect((await request.get('/api/install')).status()).toBe(401)
  expect((await request.post('/api/install', { headers: { Origin: 'https://foreign.invalid', 'x-install-token': fixture.token }, data: { op: 'network' } })).status()).toBe(403)
  await page.goto('/install')
  await page.getByLabel('کد نصب', { exact: true }).fill('incorrect')
  await page.getByRole('button', { name: 'ادامه', exact: true }).click()
  await expect(page.getByText('کد نصب درست نیست', { exact: true })).toBeVisible()
  await page.getByLabel('کد نصب', { exact: true }).fill(fixture.token)
  await page.getByRole('button', { name: 'ادامه', exact: true }).click()
  await expect(page.getByRole('heading', { name: /خوش آمدید/ })).toBeVisible()
  await page.getByRole('button', { name: 'شروع نصب', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'دامنه و SSL', exact: true })).toBeVisible()
  await page.getByLabel('دامنهٔ سایت', { exact: true }).fill('owned.example.invalid')
  await page.getByLabel('ایمیل گواهی SSL', { exact: true }).fill('operator@example.invalid')
  await page.getByRole('checkbox', { name: /شرایط صدور/ }).check()
  await page.getByRole('button', { name: 'اعمال دامنه و SSL', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: /صدور گواهی انجام نشد/ })).toBeVisible({ timeout: 45_000 })
  await expect(page.getByRole('heading', { name: 'دامنه و SSL', exact: true })).toBeVisible()
  await page.getByRole('radio', { name: /گواهی آماده دارم/ }).check()
  await page.getByLabel('فایل گواهی و زنجیرهٔ PEM', { exact: true }).setInputFiles({ name: 'owned-domain.pem', mimeType: 'application/x-pem-file', buffer: Buffer.from(fixture.certificate) })
  await expect(page.getByText('owned-domain.pem', { exact: true })).toBeVisible()
  await page.getByLabel('فایل کلید خصوصی PEM', { exact: true }).setInputFiles({ name: 'owned-key.pem', mimeType: 'application/x-pem-file', buffer: Buffer.from(fixture.privateKey) })
  await expect(page.getByText('owned-key.pem', { exact: true })).toBeVisible()
  for (const theme of ['light', 'dark'] as const) for (const width of [1440, 390]) {
    await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
    await page.setViewportSize({ width, height: 1050 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    await page.evaluate(source => { const script = document.createElement('script'); script.nonce = document.querySelector<HTMLScriptElement>('script[nonce]')?.nonce || ''; script.textContent = source; document.head.append(script) }, fs.readFileSync(require.resolve('axe-core/axe.min.js'), 'utf8'))
    const violations = await page.evaluate(async () => (await (window as any).axe.run(document.querySelector('main'), { iframes: false, runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations)
    expect(violations).toEqual([])
    await page.screenshot({ path: info.outputPath(`installer-network-${theme}-${width}.png`), fullPage: true })
  }
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.getByRole('button', { name: 'اعمال دامنه و SSL', exact: true }).click()
  await expect(page.getByText('دامنه و HTTPS آماده است', { exact: true })).toBeVisible({ timeout: 120_000 })
  await page.reload()
  await page.getByRole('button', { name: 'شروع نصب', exact: true }).click()
  await expect(page.getByText('دامنه و HTTPS آماده است', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'ادامه', exact: true }).click()
  await page.getByLabel('نام سایت', { exact: true }).fill('نصب وب موبوکام آزمایشی')
  await expect(page.getByLabel('نشانی عمومی سایت', { exact: true })).toHaveValue('https://owned.example.invalid')
  await expect(page.getByLabel('نشانی عمومی سایت', { exact: true })).toHaveAttribute('readonly', '')
  await page.getByRole('button', { name: 'ادامه', exact: true }).click()
  await page.getByLabel('نام', { exact: true }).fill('مدیر آزمایشی')
  await page.getByLabel('ایمیل', { exact: true }).fill('owned-setup-owner@example.invalid')
  await page.getByLabel('گذرواژه', { exact: true }).fill('Owned-Quartz-Web-Setup-2049')
  await page.getByLabel('تکرار گذرواژه', { exact: true }).fill('Owned-Quartz-Web-Setup-2049')
  await page.getByRole('button', { name: 'ادامه', exact: true }).click()
  await page.getByRole('button', { name: 'ادامه', exact: true }).click()
  await page.getByRole('button', { name: 'نصب سایت', exact: true }).click()
  await expect(page.getByRole('heading', { name: /نصب کامل شد/ })).toBeVisible({ timeout: 60_000 })
  await expect(page.getByRole('link', { name: 'ورود به پنل مدیریت', exact: true })).toHaveAttribute('href', 'https://owned.example.invalid/login?next=/admin')
  expect(errors).toEqual([])
})
